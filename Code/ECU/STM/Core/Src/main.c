void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM2) {                       // solo si la que sonó es la del TIM2
    uint16_t a1 = adc_buf[0], a2 = adc_buf[1], b = adc_buf[2];

    txData[0] = a1 >> 8;  txData[1] = a1 & 0xFF;
    txData[2] = a2 >> 8;  txData[3] = a2 & 0xFF;
    txData[4] = b  >> 8;  txData[5] = b  & 0xFF;

    if (HAL_CAN_GetTxMailboxesFreeLevel(&hcan) > 0) {
      HAL_CAN_AddTxMessage(&hcan, &txHeader, txData, &txMailbox);
    }
  }
}
